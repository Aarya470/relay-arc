// ─────────────────────────────────────────────────────────────────────────────
// Relay Triage Engine — our own emergency classifier. No API, no network.
//
// A multinomial logistic regression over binary n-gram features, trained in
// ml/train.py and exported to model.json. It runs in ~1ms on-device, works with
// zero signal, and can explain exactly which words drove the decision.
//
// Deliberately NOT a replacement for an LLM everywhere: when confidence is
// below the abstain threshold, callers should fall back to the language model.
// The feature spec is mirrored from ml/featurize.py and validated by
// tests/triage.test.ts against fixtures generated by the trainer.
// ─────────────────────────────────────────────────────────────────────────────
const model = /*__MODEL__*/ null as any

export type EmergencyType =
  | 'chest_pain' | 'unconscious' | 'breathing' | 'pots' | 'stroke' | 'mecfs' | 'other'

export interface TriageResult {
  type: EmergencyType
  confidence: number
  /** True when the model is not confident enough to decide alone. */
  abstain: boolean
  /** Words/phrases that drove the decision, strongest first. */
  evidence: string[]
  /** Full distribution, for logging and evaluation. */
  scores: Record<string, number>
  /** Milliseconds spent classifying. */
  ms: number
}

const CLASSES = model.classes as EmergencyType[]
const VOCAB = model.vocab as Record<string, number>
const WEIGHTS = model.weights as number[][]
const BIAS = model.bias as number[]
const NORMALISE = model.config.normalise as Record<string, string>
const NEGATORS = new Set(model.config.negators as string[])
const IMMUNE = new Set(model.config.negationImmune as string[])
const STOP = new Set(model.config.stop as string[])
const NEG_WINDOW = model.config.negWindow as number
export const ABSTAIN_THRESHOLD = model.meta.abstainThreshold as number
export const MODEL_META = model.meta

/** Mirrors ml/featurize.py: tokenize() */
function tokenize(text: string): string[] {
  // Devanagari (U+0900–U+097F) is preserved: Hindi and Marathi speech
  // transcription returns it, and stripping it would erase the input entirely.
  const cleaned = text.toLowerCase().replace(/’/g, "'")
    .replace(/[^a-z0-9'\u0900-\u097f ]+/g, ' ')
  const out: string[] = []
  for (const w of cleaned.split(' ')) {
    if (!w) continue
    const n = NORMALISE[w] ?? w
    if (n) out.push(n)   // '' means "grammatical filler, drop it"
  }
  return out
}

/** Mirrors ml/featurize.py: features() */
export function featurize(text: string): string[] {
  const toks = tokenize(text)
  const feats: string[] = []
  let negUntil = -1
  for (let i = 0; i < toks.length; i++) {
    const tok = toks[i]
    if (NEGATORS.has(tok)) { negUntil = i + NEG_WINDOW; continue }
    if (STOP.has(tok)) continue
    const negated = i <= negUntil && !IMMUNE.has(tok)
    feats.push((negated ? 'NOT_' : '') + tok)
  }
  const n = feats.length
  for (let i = 0; i < n - 1; i++) feats.push(feats[i] + '_' + feats[i + 1])
  return Array.from(new Set(feats)).sort()
}

function softmax(z: number[]): number[] {
  const m = Math.max(...z)
  const e = z.map(v => Math.exp(v - m))
  const s = e.reduce((a, b) => a + b, 0)
  return e.map(v => v / s)
}

/**
 * Classify a spoken or typed emergency description.
 * Returns the class, a calibrated confidence, and the evidence behind it.
 */
export function triage(text: string): TriageResult {
  const t0 = typeof performance !== 'undefined' ? performance.now() : Date.now()
  const feats = featurize(text)

  const z = BIAS.slice()
  const hits: { term: string; row: number[] }[] = []
  for (const f of feats) {
    const idx = VOCAB[f]
    if (idx === undefined) continue
    const row = WEIGHTS[idx]
    hits.push({ term: f, row })
    for (let c = 0; c < z.length; c++) z[c] += row[c]
  }

  const probs = softmax(z)
  let best = 0
  for (let c = 1; c < probs.length; c++) if (probs[c] > probs[best]) best = c

  // Evidence: the terms that pushed hardest toward the winning class, with
  // bigrams preferred over their component unigrams for readability.
  const evidence = hits
    .map(h => ({ term: h.term, w: h.row[best] }))
    .filter(h => h.w > 0.05 && !h.term.startsWith('NOT_'))
    .sort((a, b) => b.w - a.w)
    .slice(0, 4)
    .map(h => h.term.replace(/_/g, ' '))

  const scores: Record<string, number> = {}
  CLASSES.forEach((c, i) => { scores[c] = Math.round(probs[i] * 1000) / 1000 })

  const t1 = typeof performance !== 'undefined' ? performance.now() : Date.now()
  return {
    type: CLASSES[best],
    confidence: Math.round(probs[best] * 1000) / 1000,
    abstain: probs[best] < ABSTAIN_THRESHOLD,
    evidence,
    scores,
    ms: Math.round((t1 - t0) * 100) / 100,
  }
}
